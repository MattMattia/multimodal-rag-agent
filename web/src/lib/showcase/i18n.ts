/**
 * Showcase-engine strings in Spanish and English. The engine defaults to English when no locale is given
 * (legacy callers and tests); the BFF always passes the request locale.
 */
import type { ChatLanguage } from "../contracts";
import type { Locale } from "../i18n/types";

export type { ChatLanguage };
export type ShowcaseLocale = Locale;
export const SHOWCASE_DEFAULT_LOCALE: ShowcaseLocale = "en";

const SPANISH_HINT = /[¿¡ñáéíóú]|\b(qué|cómo|cuál|cuáles|cuánto|cuántos|dónde|por qué|genera|describe el|los|las|del|para|una|el índice|ingresos|informe)\b/i;

/** Lightweight heuristic used for `language: "auto"`: Spanish markers win, everything else is English. */
export function detectLocale(text: string): ShowcaseLocale {
  return SPANISH_HINT.test(text) ? "es" : "en";
}

export function resolveLocale(language: ChatLanguage | null | undefined, text: string): ShowcaseLocale {
  if (language === "es" || language === "en") return language;
  if (language === "auto") return detectLocale(text);
  return SHOWCASE_DEFAULT_LOCALE;
}

